export const FOODS: FoodItem[] = ROWS.map(([id, name, category, kcal, protein, carbs, fat, servings, fiber, brand]) => ({
  id,
  name,
  brand,
  category,
  per100g: { kcal, protein, carbs, fat, fiber: fiber || undefined } satisfies Macros,
  servings: dedupe([...servings, g100, oz]),
}));

function dedupe(list: Serving[]): Serving[] {
  const seen = new Set<string>();
  return list.filter((s) => (seen.has(s.label) ? false : (seen.add(s.label), true)));
}

export const FOOD_MAP: Record<string, FoodItem> = Object.fromEntries(FOODS.map((f) => [f.id, f]));

/** Simple ranked search: every word must match; earlier matches rank higher. */
export function searchFoods(query: string, extra: FoodItem[] = [], limit = 40): FoodItem[] {
  const q = query.trim().toLowerCase();
  const all = [...extra, ...FOODS];
  if (!q) return all.slice(0, limit);
  const words = q.split(/\s+/);
  const scored = all
    .map((f) => {
      const hay = `${f.name} ${f.brand ?? ''} ${f.category}`.toLowerCase();
      if (!words.every((w) => hay.includes(w))) return null;
      const idx = hay.indexOf(words[0]);
      const starts = f.name.toLowerCase().startsWith(q) ? -100 : 0;
      return { f, score: starts + idx + f.name.length / 100 };
    })
    .filter((x): x is { f: FoodItem; score: number } => !!x)
    .sort((a, b) => a.score - b.score);
  return scored.slice(0, limit).map((x) => x.f);
}
